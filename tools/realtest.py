import asyncio, json, os
from playwright.async_api import async_playwright
os.makedirs('shots', exist_ok=True)
out = []
def log(*a): s = ' '.join(str(x) for x in a); print(s); out.append(s)
async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch(args=['--autoplay-policy=no-user-gesture-required'])
        ctx = await b.new_context(viewport={'width': 1440, 'height': 860}, locale='vi-VN')
        pg = await ctx.new_page(); errs = []
        pg.on('pageerror', lambda e: errs.append('PAGEERR ' + str(e)[:200]))
        pg.on('console', lambda m: errs.append(m.text[:160]) if m.type == 'error' else None)
        await pg.goto('http://localhost:8000/studio/'); await pg.wait_for_timeout(800)
        await pg.keyboard.type('111213'); await pg.wait_for_timeout(9000)
        await pg.screenshot(path='shots/d1.png')
        log('ctl:', await pg.evaluate('!!__studio.SP.ctl'), 'iframe:', await pg.evaluate("(document.querySelector('#spHost iframe')||{}).src"))
        log('lf:', (await pg.inner_text('#lfBody'))[:200].replace('\n', ' | '))
        imgs = await pg.evaluate("[...document.querySelectorAll('.nm-item img')].slice(0,6).map(i=>i.naturalWidth+'x'+i.naturalHeight+' '+i.src.slice(0,70))")
        log('song imgs:', imgs)
        log('lb imgs:', await pg.evaluate("[...document.querySelectorAll('.lb-item img')].slice(0,3).map(i=>i.naturalWidth)"))
        await pg.click('[data-tab="album"]'); await pg.wait_for_timeout(4000)
        log('album imgs:', await pg.evaluate("[...document.querySelectorAll('.nm-item img')].slice(0,6).map(i=>i.naturalWidth+'x'+i.naturalHeight+' '+i.src.slice(0,80))"))
        await pg.screenshot(path='shots/d2.png')
        await pg.locator('.nm-item [data-act="sp"]').nth(2).click(); await pg.wait_for_timeout(4000)
        log('search:', (await pg.inner_text('#spResB'))[:300].replace('\n', ' | '))
        log('audio playing:', await pg.evaluate("(()=>{const b=document.querySelector('[data-pv=\"0\"]');return b&&b.getAttribute('aria-pressed')})()"))
        await pg.screenshot(path='shots/d3.png')
        await pg.click('#spResX')
        await pg.evaluate("__studio.spLoad('spotify:track:4cOdK2wGLETKBW3PvgPWqT', true)"); await pg.wait_for_timeout(6000)
        log('after spLoad iframe:', await pg.evaluate("(document.querySelector('#spHost iframe')||{}).src"))
        await pg.screenshot(path='shots/d4.png')
        await pg.locator('#spLib .chip').nth(1).click(); await pg.wait_for_timeout(5000)
        await pg.screenshot(path='shots/d5.png')
        for site in ['npr', 'stereogum', 'kworb', 'bandcamp', 'consequence']:
            await pg.click(f'[data-site="{site}"]'); await pg.wait_for_timeout(9000)
            fr = pg.frame_locator('#nmFrame')
            try: t = await pg.evaluate("(()=>{try{return document.getElementById('nmFrame').contentWindow.length}catch(e){return 'x'}})()")
            except Exception as e: t = repr(e)[:80]
            log(site, 'top url:', pg.url, '| frames:', t)
            await pg.screenshot(path=f'shots/site-{site}.png')
        await pg.click('[data-tab="news"]'); await pg.wait_for_timeout(500)
        await pg.click('.icon[data-app="instagram"]'); await pg.wait_for_timeout(8000)
        await pg.screenshot(path='shots/d6.png')
        log('errors:', errs[:12])
        # điện thoại
        m = await b.new_context(**p.devices['iPhone 13'])
        mp = await m.new_page()
        await mp.goto('http://localhost:8000/studio/'); await mp.wait_for_timeout(600)
        await mp.touchscreen.tap(200, 400); await mp.keyboard.type('111213'); await mp.wait_for_timeout(9000)
        await mp.screenshot(path='shots/m1.png')
        await mp.click('#spBar .t'); await mp.wait_for_timeout(2500)
        await mp.screenshot(path='shots/m2.png')
        await b.close()
    open('out_gal.txt', 'w').write('\n'.join(out))
asyncio.run(main())
